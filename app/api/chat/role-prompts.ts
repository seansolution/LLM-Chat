export function getRoleConfig(role: AIRole) {
  switch (role) {
    case 'SALES':
      return AI_SALES_ROLE
    case 'SUPPORT':
      return AI_SUPPORT_ROLE
    case 'OPS':
      return AI_OPS_ROLE
    default:
      return AI_SALES_ROLE // Default to Sales
  }
}

/**
 * Deterministic Role Selection
 * 
 * Selects the appropriate AI role based on intent, confidence, and flags.
 * This function is DETERMINISTIC: same inputs always produce same output.
 * 
 * Selection Priority (in order):
 * 1. flags.opsMode === true → OPS (highest priority, overrides all)
 * 2. Intent ends with "_pricing" → SALES
 * 3. Intent includes "registration" → SALES
 * 4. Intent includes "overview" → SUPPORT
 * 5. Intent includes "support" → SUPPORT
 * 6. Intent is "restricted_legal" → SUPPORT (redirects to staff)
 * 7. Confidence < 0.5 → SUPPORT (low confidence = support mode)
 * 8. Default → SALES (ฝ่ายขาย)
 * 
 * @param params - Selection parameters
 * @param params.intent - Detected intent string (required)
 * @param params.confidence - Intent confidence score (0-1, optional)
 * @param params.flags - Feature flags (e.g., opsMode)
 * @returns Selected role (SALES | SUPPORT | OPS)
 */
export function selectRole(params: {
  intent: string
  confidence?: number
  flags?: {
    opsMode?: boolean
    [key: string]: unknown
  }
}): AIRole {
  const { intent, confidence, flags } = params

  // Validate input
  if (!intent || typeof intent !== 'string') {
    return 'SALES' // Default fallback
  }

  // ============================================================================
  // PRIORITY 1: Flags (highest priority, overrides all)
  // ============================================================================
  if (flags?.opsMode === true) {
    return 'OPS'
  }

  // ============================================================================
  // PRIORITY 2: Intent-based selection (deterministic patterns)
  // ============================================================================
  
  // SALES triggers: pricing and registration intents
  const isPricingIntent = intent.endsWith('_pricing')
  const isRegistrationIntent = intent.includes('registration')
  
  if (isPricingIntent || isRegistrationIntent) {
    return 'SALES'
  }

  // SUPPORT triggers: overview, support, and restricted intents
  const isOverviewIntent = intent.includes('overview')
  const isSupportIntent = intent.includes('support')
  const isRestrictedIntent = intent === 'restricted_legal' || intent.includes('restricted')
  
  if (isOverviewIntent || isSupportIntent || isRestrictedIntent) {
    return 'SUPPORT'
  }

  // ============================================================================
  // PRIORITY 3: Confidence-based selection (low confidence → support)
  // ============================================================================
  if (confidence !== undefined && confidence < 0.5) {
    return 'SUPPORT' // Low confidence = redirect to support
  }

  // ============================================================================
  // DEFAULT: SALES (ฝ่ายขาย)
  // ============================================================================
  return 'SALES'
}

